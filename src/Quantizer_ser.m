function [up, lw, quantized_vec] = Quantizer_ser(unquantized_vec, B_n)
% The servioce:
%
%    [up, lw, quantized_vec] = Quantizer_ser(unquantized_vec, B_n)
%
% performs the memory-less quantization of the input unquantized_vec, in order to generate the 
% resulting quantized output quantized_vec. 
% It is understood that:
% (i) unquantized_vec is the row vector of the double (or float)-type entries to
% be quantized
% (ii) quantized_vec is the row vector of the quantized returned values
% (iii) the positive integer-valued input B_n is the number of bit allowed to
% quantize each scalar entry of the input unquantized_vec
% (iv) the (double-type) up is the maximum entry of input unquantized_vec; and,   
% (v) the (double-type) lw is the minimum entry of input unquantized_vec.
%
% The service is implemented as a MATLAB function whose code quantizer 
% can be customized by the user.
%
% By default, the implemented quantizer is a uniform quantizer that:
% (i) works at full dynamic
% (ii) allows to code each quantized value through an ordered string of B_n
% bit, and, 
% (iii )whose allowed quantized outputs are signed integer-valued that fall in the set:
%            { -(2^(B_n-1)),..., -1, 0, +1,..., +((2^(B_n-1))-1) }.
% Hence, the quantized outputs generated by the implemented quantizer can be used 
% for the integer-arithmetic-only inference of the trained ML model. 
%
if((size(unquantized_vec,1) > 1) && ((size(unquantized_vec,2) > 1)))
   error('Error message from the Quantizer_ser: the set of the unquantized input must be an 1D vector. The service call aborts');
end
%
if(size(unquantized_vec,1) > size(unquantized_vec,2))
   unquantized_vec = unquantized_vec'; 
   %The input vector must be a row vector
end
%
B_n = round(max(B_n,1));
%
lw = double(min(unquantized_vec));
up = double(max(unquantized_vec));
%Compute the input dynamic of the quantizer.The additive terms are for
%robustness purpose in the case in which quantizer and de-quantizer 
%would not use the same pairs of values for up and lw

up = max(up, lw + (10^-6));
%Regularization step. It guarantees that the difference: (up-lw) is
%strictly positive

unquantized_vec = double(unquantized_vec);
%By default, the vector to be quantized must be of double type
%
%----Building up the output signed integer-valued quantized vector--------
up_q = +((2^(B_n - 1))-1);
%
%Maximum integer-type value that is allowed the quantized output 
lw_q = - (2^(B_n -1)); 
%Minimum integer-type value that is allowed the quantized output
%
delta = double((up - lw)/((2^B_n)-1));
%Positive double-type quantization step of the built-up uniform scalar quantizer 
%
center = round(((up*lw_q)-(lw*up_q))/(up-lw));
%Integer-valued centering value of the built-up quantizer
%
quantized_vec = zeros(1,length(unquantized_vec));
%The output quantized vector must be of row type and of the same length as
%the unquantized input vector
%
quantized_vec = round(max(lw_q, min(up_q, round(((1/delta)*unquantized_vec) + center))));
%The same trick utilized in the literature for making symmetric the set of the
%allowed quantized values around the quantized zero value.
%
end %End service code