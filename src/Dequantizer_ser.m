function recovered_vec = Dequantizer_ser(quantized_vec, B_n, up, lw)
%
% The service:
%
%    recovered_vec = dequantizer(quantized_vec, B_n, up, lw)
%
% performs the pseudo-inverse mapping of the paired Quantizer service.
% The service is implemented as a MATLAB function.
%
% quantized_vec is the row vector of the quantized weights of the trained ML
% model;
%
% B_n is the (positive integer-valued) number of bits used by the paired quantizer function;
%
% up is the (double-type) maximum value allowed the scalar entries of the 
% recovered (e.g., dequantized) output vector: recovered_vec; 
%
% lw is the (double-type) minimum value allowed the scalar entries of the 
% recovered (e.g., dequantized) output vector: recovered_vec; 
%
% recovered_vec is the (double-type) row vector of the dequantized versions 
% of the entries of quantized_vec.
%
% The code of Dequantizer_ser can be customized by the user.
% The implemented default version of this service is the paired one of the
% corresponding implemented default Quantizer_ser.
%
if((size(quantized_vec,1) > 1) && ((size(quantized_vec,2) > 1)))
   error('Error message from the Dequantizer_ser: the set of the quantized input must be an 1D vector. FedE run aborts');
end
%
if(size(quantized_vec,1) > size(quantized_vec,2))
   quantized_vec = quantized_vec'; %The input vector must be a row vector
end
%
B_n = round(max(B_n,1));
lw = double(lw);
up = double(max(up, lw + (10^-6)));
%
if(abs(up-lw) <= 2*eps)
  error('Error message from Dequantizer_ser: the dynamic required to the recovered vector cannot be vanishing. FedE run aborts');
end
%------Build-up the default dequantizer PAIRED to the corresponding 
%-------------------default quantizer--------------------------------------
%
if(quantized_vec ~= round(quantized_vec))
  error('Error message from Dequantizer_ser: the scalar entries of the input quantized vector must be all of integer type. FedE run aborts');
end %End if
%The quantized values generated by the implemented paired default quantizer must be, by design, of integer type. 
%
up_q = +((2^(B_n - 1))-1); %Maximum integer-type value allowed the quantized input 
lw_q = - (2^(B_n -1));     %Minimum integer-type value allowed the quantized input
%
if((max(quantized_vec) > up_q)|| (min(quantized_vec) < lw_q))
  error('Error message from Dequantizer_ser: the maximum and/or minimum values of the entries of the input quantized vector are out of the expectexd range. FedE run aborts');
end %End if

delta = double((up - lw)/((2^B_n)-1));
%Positive double-type quantization step allowed dequantizer 
%
center = round(((up*lw_q)-(lw*up_q))/(up-lw));
%Integer-valued centering value allowed the dequantizer
%
recovered_vec = zeros(1,length(quantized_vec));
%The output recovered vector must be of row type and of the same length as
%the input quantized vector
%
recovered_vec = double(delta*double(quantized_vec - center));
%By design, the scalar entries of the output recovered (e.g., dequantized)
%vector are of double type. 
%
end %End Dequantizer_ser